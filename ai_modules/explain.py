def explain_prediction(data, prediction):

    reasons = []

    if data["known_blocklist_match"] == 1:
        reasons.append("Domain exists in a known security blocklist.")

    if data["is_dga_like"] == 1:
        reasons.append("Domain appears to be generated by a malware algorithm (DGA).")

    if data["uses_punycode"] == 1:
        reasons.append("Domain uses Punycode, which can be abused for phishing.")

    if data["entropy_score"] > 4:
        reasons.append("Domain has unusually high entropy.")

    if data["digit_ratio"] > 0.20:
        reasons.append("Domain contains an unusually high number of digits.")

    if data["suspicious_tld"] == 1:
        reasons.append("Suspicious top-level domain detected.")

    if data["threat_score"] >= 70:
        reasons.append("Threat score is very high.")

    if data["query_frequency_5min"] > 100:
        reasons.append("Unusually frequent DNS queries detected.")

    if prediction == "Benign":
        reasons.append("No significant security indicators were detected.")

    return reasons